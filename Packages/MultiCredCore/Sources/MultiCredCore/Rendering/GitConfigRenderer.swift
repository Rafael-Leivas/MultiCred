import Foundation

/// Renders the file included at the end of the user's global git config.
/// An empty identity renders a file with only the header, so the user's own
/// `user.*` settings apply (a profile without git does not switch git).
public enum GitConfigRenderer {
    public static let header = "# Generated by MultiCred. Do not edit: this file is rewritten on every profile switch.\n"

    public static func render(_ identity: GitIdentity?, environment: SystemEnvironment) -> String {
        guard let identity else { return header }
        var text = header
        text += "[user]\n"
        text += "\tname = \(quote(identity.name))\n"
        text += "\temail = \(quote(identity.email))\n"
        if let key = identity.sshKeyPath {
            let path = environment.expandTilde(key)
            let command = "ssh -i \(ShellQuoting.singleQuoted(path)) -o IdentitiesOnly=yes"
            text += "[core]\n"
            text += "\tsshCommand = \(quote(command))\n"
        }
        return text
    }

    /// git config value quoting: wrap in double quotes, escape `\` and `"`.
    /// Newlines are rejected earlier by `Validation`.
    static func quote(_ value: String) -> String {
        precondition(!Validation.hasControlCharacters(value), "control characters must be rejected by Validation")
        let escaped = value
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
        return "\"\(escaped)\""
    }
}
