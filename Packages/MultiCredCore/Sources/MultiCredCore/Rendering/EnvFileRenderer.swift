import Foundation

/// What the Claude Code part of a switch should do.
public enum ClaudeTarget: Hashable, Sendable {
    /// Leave `CLAUDE_CONFIG_DIR` as it is.
    case unchanged
    /// Default account: the variable must be unset (spike: setting it to
    /// `~/.claude` would select a different, logged-out keychain item).
    case defaultAccount
    /// Canonical absolute directory.
    case directory(String)
}

/// The environment a profile wants in the user's shells.
public struct ShellEnvironment: Hashable, Sendable {
    public struct APIKeyExport: Hashable, Sendable {
        public let envVar: String
        public let keychainAccount: String
    }

    public var generation: Int
    /// Every variable MultiCred manages; unset first so keys from the previous
    /// profile never leak into the next one.
    public var managedVars: [String]
    public var claude: ClaudeTarget
    public var apiKeys: [APIKeyExport]

    public init(generation: Int, managedVars: [String], claude: ClaudeTarget, apiKeys: [APIKeyExport]) {
        self.generation = generation
        self.managedVars = managedVars
        self.claude = claude
        self.apiKeys = apiKeys
    }
}

/// Renders `env.sh` (zsh and bash) and `env.fish`. Only variable names
/// (validated), canonical paths (quoted) and UUIDs reach these files; key values
/// stay in the Keychain and are read by `security` when the shell sources the file.
public enum EnvFileRenderer {
    public static let securityTool = "/usr/bin/security"

    public static func renderPOSIX(_ env: ShellEnvironment, securityTool: String = securityTool) -> String {
        var lines = ["# Generated by MultiCred. Do not edit. generation=\(env.generation)"]
        if !env.managedVars.isEmpty {
            lines.append("unset " + env.managedVars.joined(separator: " "))
        }
        switch env.claude {
        case .unchanged: break
        case .defaultAccount: lines.append("unset CLAUDE_CONFIG_DIR")
        case let .directory(path): lines.append("export CLAUDE_CONFIG_DIR=\(ShellQuoting.singleQuoted(path))")
        }
        let tool = ShellQuoting.singleQuoted(securityTool)
        let service = ShellQuoting.singleQuoted(KeychainConstants.apiKeyService)
        for key in env.apiKeys {
            let account = ShellQuoting.singleQuoted(key.keychainAccount)
            lines.append(
                "\(key.envVar)=\"$(\(tool) find-generic-password -s \(service) -a \(account) -w 2>/dev/null)\" && export \(key.envVar) || unset \(key.envVar)"
            )
        }
        return lines.joined(separator: "\n") + "\n"
    }

    public static func renderFish(_ env: ShellEnvironment, securityTool: String = securityTool) -> String {
        var lines = ["# Generated by MultiCred. Do not edit. generation=\(env.generation)"]
        for name in env.managedVars {
            lines.append("set -q \(name); and set -e -g \(name)")
        }
        switch env.claude {
        case .unchanged: break
        case .defaultAccount: lines.append("set -q CLAUDE_CONFIG_DIR; and set -e -g CLAUDE_CONFIG_DIR")
        case let .directory(path): lines.append("set -gx CLAUDE_CONFIG_DIR \(ShellQuoting.fishSingleQuoted(path))")
        }
        let tool = ShellQuoting.fishSingleQuoted(securityTool)
        let service = ShellQuoting.fishSingleQuoted(KeychainConstants.apiKeyService)
        for key in env.apiKeys {
            let account = ShellQuoting.fishSingleQuoted(key.keychainAccount)
            // `set` keeps the command substitution's exit status in $status.
            lines.append("set -l __multicred_value (\(tool) find-generic-password -s \(service) -a \(account) -w 2>/dev/null)")
            lines.append("if test $status -eq 0")
            lines.append("    set -gx \(key.envVar) $__multicred_value")
            lines.append("else")
            lines.append("    set -q \(key.envVar); and set -e -g \(key.envVar)")
            lines.append("end")
        }
        return lines.joined(separator: "\n") + "\n"
    }
}
